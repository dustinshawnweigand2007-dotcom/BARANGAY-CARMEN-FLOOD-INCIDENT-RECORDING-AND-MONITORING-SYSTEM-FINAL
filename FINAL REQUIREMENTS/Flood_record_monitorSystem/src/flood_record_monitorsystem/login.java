    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        String uN = username.getText();
 String pW = new String(password.getPassword());
 
 if (uN.isEmpty() || pW.isEmpty()) {
    JOptionPane.showMessageDialog(
        this,
        "Please enter username and password",
        "Login Error",
        JOptionPane.ERROR_MESSAGE
    );
    return;
}
 Connection conn = Database.connect();
 
 try{
     String sql = "SELECT * FROM tbl_personnel WHERE username= ? AND password=?";
     PreparedStatement pst = conn.prepareStatement(sql);
     pst.setString(1, uN);
     pst.setString(2, pW);
  
     ResultSet rs = pst.executeQuery();
     
     if (rs.next()) {

    int personnelId = rs.getInt("personnel_id");
    String role = rs.getString("role");

    Userusage.setUser(personnelId, uN);

    if (role.equalsIgnoreCase("Admin")) {

        JOptionPane.showMessageDialog(this, "Admin successfully logged in!");

        Admindashboard admin = new Admindashboard();
        admin.setVisible(true);

    } else if (role.equalsIgnoreCase("Staff")) {

         JOptionPane.showMessageDialog(this, "Staff successfully logged in!");

         // Pass the username (uN) into the dashboard constructor
         Staffdashboard staff = new Staffdashboard(uN,role);
         staff.setVisible(true);
     }

     this.dispose();


} else {
    JOptionPane.showMessageDialog(
        this,
        "Invalid username or password.",
        "Login Error",
        JOptionPane.ERROR_MESSAGE
    );

     
     


}
     conn.close();
 } catch (Exception e) {
    JOptionPane.showMessageDialog(
        this,
        "Error: " + e.getMessage(),
        "Error",
        JOptionPane.ERROR_MESSAGE
    );

 }
    }//GEN-LAST:event_jButton5ActionPerformed

    private void usernameFocusGained(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_usernameFocusGained
        if (username.getText().equals("Enter username")) {
        username.setText("");
        username.setForeground(Color.BLACK);
    }

    }//GEN-LAST:event_usernameFocusGained

    private void usernameFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_usernameFocusLost
         if (username.getText().isEmpty()) {
        username.setText("Enter username");
        username.setForeground(Color.GRAY);
    }
    }//GEN-LAST:event_usernameFocusLost

    private void passwordFocusGained(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_passwordFocusGained
         if (new String(password.getPassword()).equals("Enter password")) {
    password.setText("");
    password.setEchoChar('*');
    password.setForeground(Color.BLACK);
}

    }//GEN-LAST:event_passwordFocusGained

    private void passwordFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_passwordFocusLost
        if (password.getPassword().length == 0) {
    password.setEchoChar((char) 0);
    password.setText("Enter password");
    password.setForeground(Color.GRAY);
}
    }//GEN-LAST:event_passwordFocusLost

